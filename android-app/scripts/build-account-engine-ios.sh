#!/usr/bin/env bash
set -euo pipefail
if [[ "$(uname -s)" != Darwin ]]; then
  echo 'iPhone 原生库需要 macOS + Xcode；可在 GitHub Actions 的 macOS 构建机上运行。' >&2
  exit 1
fi
APP_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENGINE_ROOT="${ACCOUNT_ENGINE_SOURCE:-$APP_ROOT/../account-engine}"
BUILD_ROOT="$ENGINE_ROOT/build/ios"
OUTPUT_ROOT="$APP_ROOT/ios/Frameworks"
SIM_ARCH="$(uname -m)"
[[ "$SIM_ARCH" == arm64 || "$SIM_ARCH" == x86_64 ]]
mkdir -p "$BUILD_ROOT/device" "$BUILD_ROOT/simulator" "$OUTPUT_ROOT"
build_slice() {
  local sdk="$1" arch="$2" target="$3" destination="$4" goarch
  goarch="$arch"; [[ "$arch" != x86_64 ]] || goarch=amd64
  local sdk_root clang
  sdk_root="$(xcrun --sdk "$sdk" --show-sdk-path)"
  clang="$(xcrun --sdk "$sdk" --find clang)"
  (cd "$ENGINE_ROOT" && CGO_ENABLED=1 GOOS=ios GOARCH="$goarch" \
    CC="$clang -target $target -isysroot $sdk_root" \
    CGO_CFLAGS="-target $target -isysroot $sdk_root" \
    CGO_LDFLAGS="-target $target -isysroot $sdk_root" \
    go build -buildmode=c-archive -trimpath -ldflags='-s -w' -o "$destination/libHetingEngine.a" .)
}
build_slice iphoneos arm64 arm64-apple-ios15.1 "$BUILD_ROOT/device"
build_slice iphonesimulator "$SIM_ARCH" "$SIM_ARCH-apple-ios15.1-simulator" "$BUILD_ROOT/simulator"
# Only replace the framework generated by this script.
if [[ -d "$OUTPUT_ROOT/HetingEngine.xcframework" ]]; then rm -rf "$OUTPUT_ROOT/HetingEngine.xcframework"; fi
xcodebuild -create-xcframework \
  -library "$BUILD_ROOT/device/libHetingEngine.a" \
  -library "$BUILD_ROOT/simulator/libHetingEngine.a" \
  -output "$OUTPUT_ROOT/HetingEngine.xcframework"
echo 'HetingEngine.xcframework ready (iPhone ARM64 + current Mac simulator architecture).'
